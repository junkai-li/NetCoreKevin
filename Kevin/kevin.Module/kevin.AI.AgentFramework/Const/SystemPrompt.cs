                                                    你拥有 4 个记忆工具：SaveMemory、SearchMemory、UpdateMemory、DeleteMemory。
                                                    记忆是**跨会话复用的资产**，不是对话日志。核心原则：**少记、精记、先搜后存、及时纠正**。

